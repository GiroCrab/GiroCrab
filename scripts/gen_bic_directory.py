#!/usr/bin/env python3
"""Generates girocrab-core/src/connectors/bic_directory_data.rs (BLZ -> BIC).

Input: the Bundesbank "Bankleitzahlendatei" in fixed-width TXT format, from
https://www.bundesbank.de/de/aufgaben/unbarer-zahlungsverkehr/serviceangebot/bankleitzahlen/download-bankleitzahlen-602592
(file "blz-aktuell-txt-data.txt", updated quarterly).

Usage: python3 -I scripts/gen_bic_directory.py path/to/blz-aktuell-txt-data.txt
"""
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "girocrab-core/src/connectors/bic_directory_data.rs"


def main(src: str) -> None:
    bics: dict[str, str] = {}
    for line in pathlib.Path(src).read_text(encoding="latin-1").splitlines():
        if len(line) < 150:
            continue
        blz, primary, bic = line[0:8], line[8], line[139:150].strip()
        # only the main entry ("Merkmal" 1) of a BLZ carries the BIC
        if primary != "1" or not re.fullmatch(r"[A-Z]{6}[A-Z0-9]{2}([A-Z0-9]{3})?", bic):
            continue
        bics[blz] = bic[:8] if bic.endswith("XXX") else bic
    if len(bics) < 1000:
        sys.exit(f"only {len(bics)} entries parsed – wrong file format?")
    rows = "\n".join(f'    ("{b}", "{bics[b]}"),' for b in sorted(bics))
    OUT.write_text(
        "//! GENERATED by scripts/gen_bic_directory.py – do not edit by hand.\n"
        "//!\n"
        "//! BLZ -> BIC from the Deutsche Bundesbank \"Bankleitzahlendatei\" (published\n"
        "//! for free download; main entries only, \"XXX\" branch suffix dropped).\n\n"
        "#[rustfmt::skip]\n"
        "pub(super) const BICS: &[(&str, &str)] = &[\n"
        f"{rows}\n"
        "];\n"
    )
    print(f"{len(bics)} entries -> {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
