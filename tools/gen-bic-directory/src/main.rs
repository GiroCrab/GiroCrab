//! Generates `girocrab-core/data/bic_directory.tsv` (BLZ -> BIC and bank name).
//!
//! Input: the Bundesbank "Bankleitzahlendatei" in fixed-width TXT format, from
//! https://www.bundesbank.de/de/aufgaben/unbarer-zahlungsverkehr/serviceangebot/bankleitzahlen/download-bankleitzahlen-602592
//! (file "blz-aktuell-txt-data.txt", updated quarterly).
//!
//! Usage (the validity period from the download page goes into the header):
//!   cargo run -p gen-bic-directory -- path/to/blz-aktuell-txt-data.txt "07.09.2026–06.12.2026"

use std::collections::BTreeMap;
use std::path::Path;
use std::{env, fs, process};

/// 4 letters bank, 2 letters country, 2 alphanumeric location, optional 3 alphanumeric branch.
fn is_bic(s: &str) -> bool {
    let b = s.as_bytes();
    (b.len() == 8 || b.len() == 11)
        && b[..6].iter().all(u8::is_ascii_uppercase)
        && b[6..]
            .iter()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit())
}

fn main() {
    let (Some(src), Some(valid)) = (env::args().nth(1), env::args().nth(2)) else {
        eprintln!(
            "usage: cargo run -p gen-bic-directory -- <blz-aktuell-txt-data.txt> <valid period>"
        );
        process::exit(2);
    };
    let bytes = fs::read(&src).unwrap_or_else(|e| {
        eprintln!("cannot read {src}: {e}");
        process::exit(1);
    });
    // The file is ISO 8859-1: every byte is one char, so fixed-width columns are byte offsets.
    let text: String = bytes.iter().map(|&b| b as char).collect();

    let mut bics = BTreeMap::new();
    for line in text.lines() {
        let line: Vec<char> = line.chars().collect();
        if line.len() < 150 {
            continue;
        }
        let field = |a: usize, b: usize| line[a..b].iter().collect::<String>();
        // "Bezeichnung" (58 chars): the short name (107..134) abbreviates too much
        let (blz, primary, name, bic) = (field(0, 8), line[8], field(9, 67), field(139, 150));
        let bic = bic.trim();
        // only the main entry ("Merkmal" 1) of a BLZ carries the BIC
        if primary != '1' || !is_bic(bic) {
            continue;
        }
        let bic = bic.strip_suffix("XXX").unwrap_or(bic);
        // "-alt-" (also "-alt", "-alt-.") marks a merged bank whose BLZ lives on;
        // the successor is rarely given, so keep the name its customers know
        let name = name.trim();
        let name = match name.rsplit_once("-alt") {
            Some((head, "" | "-" | "-.")) => head.trim_end(),
            _ => name,
        };
        bics.insert(blz, (bic.to_string(), name.to_string()));
    }
    if bics.len() < 1000 {
        eprintln!("only {} entries parsed – wrong file format?", bics.len());
        process::exit(1);
    }

    let mut out = String::from(
        "# GENERATED by tools/gen-bic-directory – do not edit by hand.\n\
         #\n\
         # BLZ -> BIC and bank name from the Deutsche Bundesbank \"Bankleitzahlendatei\"\n\
         # (published for free download; main entries only, \"XXX\" branch suffix and\n\
         # \"-alt-\" merger marker dropped).\n\
         # Columns (tab-separated): blz, bic, name. Sorted by BLZ.\n",
    );
    out.push_str(&format!("# Source file valid {valid}.\n"));
    for (blz, (bic, name)) in &bics {
        out.push_str(&format!("{blz}\t{bic}\t{name}\n"));
    }

    let dest =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../girocrab-core/data/bic_directory.tsv");
    fs::write(&dest, out).unwrap_or_else(|e| {
        eprintln!("cannot write {}: {e}", dest.display());
        process::exit(1);
    });
    println!("{} entries -> {}", bics.len(), dest.display());
}
